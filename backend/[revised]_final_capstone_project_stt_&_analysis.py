import ffmpeg
import whisper

def process_file(input_file, output_index):
    output_file = f"audio_clean_{output_index}.wav"

    # Extract audio
    ffmpeg.input(input_file).output(output_file, ac=1, ar=16000).run(overwrite_output=True)

    # Load Whisper
    model = whisper.load_model("medium")
    audio = whisper.load_audio(output_file)
    result = model.transcribe(
        audio=output_file,
        language="en",
        word_timestamps=True
    )

    pause_word_gap = 0.5
    pause_segment_gap = 0.5

    segments = []
    current_segment = []
    seg_start = None
    prev_end = None

    def to_timestamp(sec):
        m = int(sec // 60)
        s = int(sec % 60)
        return f"{m:02d}:{s:02d}"

    # Segment
    for seg in result["segments"]:
        words = seg.get("words", [])
        if not words:
            continue

        if prev_end is not None and words[0]["start"] - prev_end > pause_segment_gap:
            if current_segment:
                seg_end = prev_end
                text = " ".join(current_segment).strip()
                segments.append((seg_start, seg_end, text))
                current_segment = []
                seg_start = None

        for i, w in enumerate(words):
            if seg_start is None:
                seg_start = w["start"]

            current_segment.append(w["word"])

            if i < len(words) - 1:
                gap = words[i + 1]["start"] - w["end"]
                if gap > pause_word_gap:
                    seg_end = w["end"]
                    text = " ".join(current_segment).strip()
                    segments.append((seg_start, seg_end, text))
                    current_segment = []
                    seg_start = words[i + 1]["start"]

        prev_end = words[-1]["end"]

    if current_segment:
        seg_end = prev_end
        text = " ".join(current_segment).strip()
        segments.append((seg_start, seg_end, text))

    # jeda
    pauses = []
    for i in range(1, len(segments)):
        pause_dur = segments[i][0] - segments[i - 1][1]
        if pause_dur > 0:
            pauses.append(pause_dur)

    total_silence = len(pauses)


    try:
        info = ffmpeg.probe(input_file)
        duration_sec = float(info["format"]["duration"])
    except:
        duration_sec = len(audio) / 16000

    # Output Text
    final_text = ""
    for idx, (start, end, text) in enumerate(segments):
        final_text += f"[{to_timestamp(start)} - {to_timestamp(end)}] {text}\n"
        if idx < len(pauses):
            final_text += f"[PAUSE {pauses[idx]:.2f}s]\n"

    final_text += f"\nTotal jeda terdeteksi: {total_silence}\n"
    final_text += f"Durasi total video: {duration_sec:.2f} detik\n"

    out_name = f"hasil_segment_timestamp_sensitif_{output_index}.txt"
    with open(out_name, "w", encoding="utf-8") as f:
        f.write(final_text)

    print(f"Konversi : {input_file} → {out_name}")


    return {
        "file": input_file,
        "segments": segments,
        "pauses": pauses,
        "total_silence": total_silence,
        "duration": duration_sec,
        "text_output": final_text,
        "full_transcript": result.get("text", final_text)  # fallback
    }




