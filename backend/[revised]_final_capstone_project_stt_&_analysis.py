"""## Raw Cleaning & Raw Analysis (Fluency + AI Suspect)"""

def clean_text_raw(text):
    text = text.lower()
    text = re.sub(r'\[.*?\]', '', text)
    text = re.sub(r'\(.*?\)', '', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text

"""Fluency"""

def analyze_fluency_from_silence(total_silence, total_duration, gaps):
    silence_ratio = total_silence / total_duration
    avg_gap = total_silence / len(gaps) if len(gaps) > 0 else 0
    gap_freq = len(gaps) / total_duration

    score = 4

    # Silence ratio (persentase jeda)
    if silence_ratio > 0.25:
        score -= 3
    elif silence_ratio > 0.15:
        score -= 2
    elif silence_ratio > 0.08:
        score -= 1

    # Average gap length
    if avg_gap > 2.0:
        score -= 2
    elif avg_gap > 1.2:
        score -= 1

    # Gap frequency
    if gap_freq > (1/4):  # lebih dari 1 gap setiap 4 detik
        score -= 1

    score = max(1, min(score, 4))

    return {
        "fluency_score": score,
        "silence_ratio": silence_ratio,
        "avg_gap": avg_gap,
        "gap_frequency": gap_freq
    }

"""## AI Detector

SILENCE-BASED AI DETECTOR
"""

def analyze_ai_suspect_from_silence(total_silence, total_duration, gaps):
    if total_duration == 0:
        return 0

    silence_ratio = total_silence / total_duration
    avg_gap = sum(gaps) / len(gaps) if gaps else 0
    gap_variance = (max(gaps) - min(gaps)) if len(gaps) > 1 else 0

    score = 0

    # 1. AI hampir tanpa jeda
    if silence_ratio < 0.02:
        score += 2

    # 2. Jeda pendek → AI
    if avg_gap < 0.40:
        score += 1

    # 3. Variasi jeda stabil
    if gap_variance < 0.3:
        score += 1

    # 4. Jeda seragam → AI
    if len(gaps) > 0 and all(0.20 < g < 0.55 for g in gaps):
        score += 1

    return min(score, 4)

"""EMBEDDING-BASED AI STYLE DETECTOR

3.1 Utility cosine
"""

def cosine_similarity(a, b):
    return np.dot(a, b) / (norm(a) * norm(b))

"""Build AI-style centroid"""

def build_ai_style_embedding(prompts):
    vectors = []
    for p in prompts:
        resp = client.embeddings.create(
            model=EMBED_MODEL,
            input=p
        )
        vectors.append(np.array(resp.data[0].embedding))
    return np.mean(vectors, axis=0)

