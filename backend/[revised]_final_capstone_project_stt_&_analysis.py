"""3.5 Detector dari embedding similarity"""

def analyze_ai_suspect_from_embedding(text, ai_centroid):
    resp = client.embeddings.create(
        model=EMBED_MODEL,
        input=text
    )
    emb = np.array(resp.data[0].embedding)

    sim = cosine_similarity(emb, ai_centroid)

    # Skor AI-likeness dari similarity
    if sim > 0.90:
        score = 3
    elif sim > 0.87:
        score = 2
    elif sim > 0.83:
        score = 1
    else:
        score = 0

    return {
        "similarity": sim,
        "embedding_score": score
    }

"""FINAL AI-COMBINED DETECTOR"""

def analyze_ai_combined(text, total_silence, total_duration, gaps, ai_centroid):
    silence_score = analyze_ai_suspect_from_silence(total_silence, total_duration, gaps)
    emb_data = analyze_ai_suspect_from_embedding(text, ai_centroid)

    embedding_score = emb_data["embedding_score"]
    total_score = silence_score + embedding_score

    if total_score >= 6:
        label = "Highly AI-like"
    elif total_score >= 4:
        label = "Likely AI-like"
    elif total_score >= 2:
        label = "Somewhat AI-like"
    else:
        label = "Likely Human"

    return {
        "silence_score": silence_score,
        "embedding_similarity": emb_data["similarity"],
        "embedding_score": embedding_score,
        "ai_score_total": total_score,
        "ai_label": label
    }

"""## Clean Text for Semantic Analysis"""

def clean_text_semantic(text):
    text = text.lower()
    filler = ["uh", "um", "emm", "hmm", "erm", "you know", "like", "kinda", "sorta"]
    for f in filler:
        text = text.replace(f, "")

    text = re.sub(r'\b(\w+)\s+\1\b', r'\1', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text

"""## Semantic Similarity Helper"""

def semantic_sim(a, b):
    emb1 = embedder.encode(a, convert_to_tensor=True, normalize_embeddings=True)
    emb2 = embedder.encode(b, convert_to_tensor=True, normalize_embeddings=True)
    return float(util.cos_sim(emb1, emb2).item())

